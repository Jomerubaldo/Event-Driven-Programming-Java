package Week04.SwitchCaseStructure;

public class SwitchCaseWithNoBreak {
    public static void main(String[] args) {
        int n = 2;
        int x;

        switch (n) {
            case 1:
                x = 10;
                System.out.println(x);

            case 2:
                x = 20;
                System.out.println(x);

            case 3:
                x = 30;
                System.out.println(x);

        }
    }
}
