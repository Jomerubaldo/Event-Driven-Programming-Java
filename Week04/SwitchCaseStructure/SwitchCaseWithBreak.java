package Week04.SwitchCaseStructure;

public class SwitchCaseWithBreak {
    public static void main(String[] args) {

        int n = 2;
        int x; // pipili eaither sa case na mapili

        switch (n) {
            case 1:
                x = 10;
                System.out.println("The value of " + n + " " + "is" + " " + x);
                break;
            case 2:
                x = 20;
                System.out.println("The value of " + n + " " + "is" + " " + x);
                break;
            case 3:
                x = 30;
                System.out.println("The value of " + n + " " + "is" + " " + x);
                break;
        }
    }
}
