package Week04.Repetition;

public class WhileLoop {
    public static void main(String[] args) {

        int i = 0;

        while (i <= 20) {
            System.out.print(i + " ");
            i = i + 5;
        }
        System.out.println(); // print all pag false na ang condition

    }
}

// Output: 0 5 10 15 20